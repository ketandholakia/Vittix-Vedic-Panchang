<?php

/**
 * Generate engine regression snapshots.
 *
 * IMPORTANT:
 * These snapshots are produced by the engine under test. They are useful
 * for detecting behavioural changes, but they are not independent proof
 * of astronomical correctness.
 *
 * Run:
 * php scripts/generate_regression_snapshots.php
 */

declare(strict_types=1);

require_once __DIR__ . '/../vendor/autoload.php';

use Vittix\Panchang\Panchang;
use Vittix\Panchang\Tests\Support\TestLocations;

$panchang = Panchang::createDefault();
$location = TestLocations::ahmedabad();
$timezone = new DateTimeZone('Asia/Kolkata');

$referenceDates = [
    '2026-07-31',
    '2026-01-14',
    '2026-03-30',
    '2026-11-01',
    '2023-07-04',
    '2024-01-25',
    '2025-08-16',
    '2000-01-01',
];

$snapshots = [
    'metadata' => [
        'fixture_type' => 'engine_generated_snapshot',
        'warning' =>
            'Generated by the engine under test; not an independent oracle.',
        'generated_at' => (new DateTimeImmutable('now', $timezone))->format('c'),
        'timezone' => $timezone->getName(),
        'location' => [
            'name' => 'Ahmedabad',
            'latitude' => 23.0225,
            'longitude' => 72.5714,
            'elevation_m' => 53.0,
        ],
        'conventions' => [
            'ayanamsha' => 'Lahiri',
            'month_system' => 'Amanta',
            'evaluation_rule' => 'local_sunrise',
        ],
    ],
    'dates' => [],
];

foreach ($referenceDates as $dateString) {
    $date = new DateTimeImmutable($dateString . ' 00:00:00', $timezone);
    $day = $panchang->day($date, $location);

    $snapshots['dates'][$dateString] = [
        'tithi' => [
            'index' => $day->tithiAtSunrise->value,
            'number' => $day->tithiAtSunrise->number(),
            'name_en' => $day->tithiAtSunrise->nameEnglish(),
            'paksha' => $day->paksha->label(),
            'ends_at' => $day->tithiEndsAt?->format('c'),
        ],
        'nakshatra' => [
            'index' => $day->nakshatraAtSunrise->value,
            'name_en' => $day->nakshatraAtSunrise->nameEnglish(),
            'pada' => $day->padaAtSunrise,
            'ends_at' => $day->nakshatraEndsAt?->format('c'),
        ],
        'yoga' => [
            'index' => $day->yogaAtSunrise->value,
            'name_en' => $day->yogaAtSunrise->nameEnglish(),
            'ends_at' => $day->yogaEndsAt?->format('c'),
        ],
        'karana' => [
            'index' => $day->karanaAtSunrise->value,
            'name_en' => $day->karanaAtSunrise->nameEnglish(),
            'ends_at' => $day->karanaEndsAt?->format('c'),
        ],
        'vara' => [
            'index' => $day->vara->value,
            'name_en' => $day->vara->nameEnglish(),
        ],
        'solar_events' => [
            'sunrise' => $day->solarEvents->sunrise?->format('c'),
            'sunset' => $day->solarEvents->sunset?->format('c'),
        ],
        'lunar_month' => [
            'index' => $day->lunarMonth?->value,
            'name_en' => $day->lunarMonth?->nameEnglish(),
            'is_adhika' => $day->isAdhikaMasa,
        ],
    ];

    printf(
        "[SNAPSHOT] %s: %s, %s Paksha, %s Pada %d, sunrise %s\n",
        $dateString,
        $day->tithiAtSunrise->nameEnglish(),
        $day->paksha->label(),
        $day->nakshatraAtSunrise->nameEnglish(),
        $day->padaAtSunrise,
        $day->solarEvents->sunrise?->format('H:i') ?? 'N/A',
    );
}

$outputPath =
    __DIR__ . '/../tests/fixtures/generated/panchang_snapshots.json';

$outputDirectory = dirname($outputPath);

if (
    !is_dir($outputDirectory)
    && !mkdir($outputDirectory, 0775, true)
    && !is_dir($outputDirectory)
) {
    throw new RuntimeException(
        sprintf('Unable to create directory: %s', $outputDirectory)
    );
}

$json = json_encode(
    $snapshots,
    JSON_PRETTY_PRINT
    | JSON_UNESCAPED_UNICODE
    | JSON_UNESCAPED_SLASHES
    | JSON_THROW_ON_ERROR
);

$bytesWritten = file_put_contents($outputPath, $json . PHP_EOL);

if ($bytesWritten === false) {
    throw new RuntimeException(
        sprintf('Unable to write snapshots to: %s', $outputPath)
    );
}

printf(
    "\nRegression snapshots written to: %s\n",
    $outputPath
);
