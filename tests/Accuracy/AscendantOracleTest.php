<?php

declare(strict_types=1);

namespace Vittix\Panchang\Tests\Accuracy;

use DateTimeImmutable;
use DateTimeZone;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\Attributes\CoversClass;
use Vittix\Panchang\Astronomy\Coordinates\AscendantCalculator;
use Vittix\Panchang\Astronomy\Coordinates\NutationCalculator;
use Vittix\Panchang\Astronomy\Coordinates\ObliquityCalculator;
use Vittix\Panchang\Astronomy\Sidereal\SiderealTimeCalculator;
use Vittix\Panchang\Time\AstroTimeFactory;
use Vittix\Panchang\ValueObject\GeoLocation;

/**
 * Ascendant oracle against Swiss Ephemeris.
 *
 * Fixture: tests/fixtures/reference/ascendant_positions.json, generated by
 * tools/reference/generate_fixtures.py (200 random instant/location pairs,
 * 1950–2100, latitudes ±60°, longitudes global). The reference values are
 * swe.houses_ex(jd_ut, lat, lon, 'P', SEFLG_SIDEREAL) after
 * set_sid_mode(SIDM_LAHIRI) — Asc and MC are house-system independent.
 *
 * Tolerance 0.05° (3′) covers the documented ~12″ Lahiri polynomial offset
 * plus the engine's mean-vs-true ayanamsha simplification, with headroom.
 */
#[Group('accuracy')]
#[CoversClass(AscendantCalculator::class)]
final class AscendantOracleTest extends AccuracyTestCase
{
    private const TOLERANCE_DEG = 0.05;

    private ?AscendantCalculator $ascendant = null;

    private AstroTimeFactory $timeFactory;

    private function ascendant(): AscendantCalculator
    {
        $nutation = new NutationCalculator();

        return $this->ascendant ??= new AscendantCalculator(
            new SiderealTimeCalculator(),
            new ObliquityCalculator($nutation),
            $this->engine()
        );
    }

    protected function setUp(): void
    {
        $this->timeFactory = new AstroTimeFactory();
    }

    public function testSiderealAscendantMatchesSwissEphemeris(): void
    {
        $this->skipWithoutFixture('ascendant_positions');

        $samples = $this->repo()->samples('ascendant_positions');
        self::assertNotEmpty($samples);

        $failures = [];
        foreach ($samples as $i => $sample) {
            $instant = $this->timeFactory->fromDateTime(
                new DateTimeImmutable((string) $sample['utc'], new DateTimeZone('UTC'))
            );
            $location = new GeoLocation(
                latitude: (float) $sample['latitude'],
                longitude: (float) $sample['longitude'],
                elevationMeters: 0.0
            );

            $actual = $this->ascendant()->siderealLongitude($instant, $location);
            $expected = (float) $sample['ascendant_sidereal'];

            $diff = abs(fmod($actual - $expected + 540.0, 360.0) - 180.0);
            if ($diff > self::TOLERANCE_DEG) {
                $failures[] = sprintf(
                    "#%d %s lat %.4f lon %.4f: expected %.6f, got %.6f (diff %.4f°)",
                    $i,
                    (string) $sample['utc'],
                    (float) $sample['latitude'],
                    (float) $sample['longitude'],
                    $expected,
                    $actual,
                    $diff
                );
            }
        }

        self::assertSame(
            [],
            $failures,
            sprintf(
                "%d of %d Ascendant samples exceed the %.2f° tolerance vs Swiss Ephemeris:\n%s",
                count($failures),
                count($samples),
                self::TOLERANCE_DEG,
                implode("\n", array_slice($failures, 0, 10))
            )
        );
    }

    public function testSiderealMcMatchesSwissEphemeris(): void
    {
        $this->skipWithoutFixture('ascendant_positions');

        $samples = $this->repo()->samples('ascendant_positions');
        self::assertNotEmpty($samples);

        // MC from the engine: the point of the ecliptic culminating, i.e.
        // the ecliptic longitude whose right ascension equals RAMC:
        // λ_MC = atan2(sin RAMC, cos RAMC · cos ε), then − ayanamsha.
        // Cross-checked against the fixture's mc_sidereal (Swiss).
        $nutation = new NutationCalculator();
        $obliquity = new ObliquityCalculator($nutation);
        $siderealTime = new SiderealTimeCalculator();
        $engine = $this->engine();

        $failures = [];
        foreach ($samples as $i => $sample) {
            $instant = $this->timeFactory->fromDateTime(
                new DateTimeImmutable((string) $sample['utc'], new DateTimeZone('UTC'))
            );
            $ramc = $siderealTime->localMeanSiderealTime(
                $instant->julianDayUt,
                (float) $sample['longitude']
            );
            $eps = $obliquity->true($instant);
            $mcTropical = \Vittix\Panchang\Math\Angle::normalize(
                \Vittix\Panchang\Math\Angle::atan2(
                    \Vittix\Panchang\Math\Angle::sin($ramc),
                    \Vittix\Panchang\Math\Angle::cos($ramc) * \Vittix\Panchang\Math\Angle::cos($eps)
                )
            );
            $actual = \Vittix\Panchang\Math\Angle::normalize($mcTropical - $engine->ayanamsa($instant));
            $expected = (float) $sample['mc_sidereal'];

            $diff = abs(fmod($actual - $expected + 540.0, 360.0) - 180.0);
            if ($diff > self::TOLERANCE_DEG) {
                $failures[] = sprintf(
                    "#%d %s lon %.4f: expected %.6f, got %.6f (diff %.4f°)",
                    $i,
                    (string) $sample['utc'],
                    (float) $sample['longitude'],
                    $expected,
                    $actual,
                    $diff
                );
            }
        }

        self::assertSame(
            [],
            $failures,
            sprintf(
                "%d of %d MC samples exceed the %.2f° tolerance vs Swiss Ephemeris:\n%s",
                count($failures),
                count($samples),
                self::TOLERANCE_DEG,
                implode("\n", array_slice($failures, 0, 10))
            )
        );
    }
}
